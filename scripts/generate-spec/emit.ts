import type { ElementSupport, Support } from "./bcd";
import { compareNames, type SpecData, type ValueType } from "./model";

/**
 * Writes the data of one SVG version as a TypeScript module with three
 * exports: `<prefix>Elements`, `<prefix>Groups` and
 * `<prefix>PresentationAttributes`. Attributes are written as objects from
 * name to value type.
 */
export const emitSpec = (
  prefix: string,
  data: SpecData,
  header: string,
): string => {
  const typed = (
    names: readonly string[],
    values: Map<string, ValueType> | undefined,
    where: string,
  ): Record<string, ValueType> =>
    Object.fromEntries(
      names.map((name) => {
        const type = values?.get(name);
        if (type === undefined) {
          throw new Error(`emit: ${name} in ${where} has no value type`);
        }
        return [name, type];
      }),
    );

  const elements = sorted(
    new Map(
      [...data.elements].map(([name, element]) => [
        name,
        {
          groups: element.groups,
          attributes: typed(
            element.attributes,
            data.values.elements.get(name),
            `element ${name}`,
          ),
          presentation: element.presentation,
        },
      ]),
    ),
  );
  const groups = sorted(
    new Map(
      [...data.groups].map(([name, attributes]) => [
        name,
        typed(attributes, data.values.groups.get(name), `group ${name}`),
      ]),
    ),
  );
  return [
    header,
    doc(
      "Elements by name, with their attribute groups and the value types of their own attributes.",
    ),
    constant(`${prefix}Elements`, elements),
    doc("Attribute groups by name, with the value types of their attributes."),
    constant(`${prefix}Groups`, groups),
    doc(
      "Presentation attributes that apply to every element in the presentation group.",
    ),
    constant(`${prefix}PresentationAttributes`, data.presentationAttributes),
  ].join("\n");
};

/**
 * Writes the browser support data as a TypeScript module with the exports
 * `svgElementSupport` and `svgGlobalAttributeSupport`.
 */
export const emitSupport = (
  elements: Map<string, ElementSupport>,
  globalAttributes: Map<string, Support>,
  header: string,
): string =>
  [
    header,
    doc(
      "Browser support of SVG elements and their attributes, by element name.",
    ),
    constant(
      "svgElementSupport",
      sorted(
        new Map(
          [...elements].map(([name, { attributes, ...element }]) => [
            name,
            { ...element, attributes: sorted(attributes) },
          ]),
        ),
      ),
    ),
    doc("Browser support of attributes that apply to every SVG element."),
    constant("svgGlobalAttributeSupport", sorted(globalAttributes)),
  ].join("\n");

/**
 * The comment at the top of every generated file: what made it and from which
 * sources, with their licenses (ARCHITECTURE §11).
 */
export const header = (sources: readonly string[]): string =>
  [
    "// Generated by scripts/generate-spec. Do not edit; run `bun run spec:generate`.",
    "//",
    "// Sources:",
    ...sources.map((source) => `// - ${source}`),
    "//",
    "// Only facts such as names, groups, value types and support versions are",
    "// taken from the sources, no spec text.",
    "",
  ].join("\n");

/**
 * Turns a map into an object with its keys sorted by `compareNames`.
 */
const sorted = <T>(map: Map<string, T>): Record<string, T> =>
  Object.fromEntries([...map].sort(([a], [b]) => compareNames(a, b)));

const doc = (text: string): string => `\n/** ${text} */`;

const constant = (name: string, value: unknown): string =>
  `export const ${name} = ${JSON.stringify(value)} as const;`;
